    /// テキストの末尾がトリガーフレーズに合致するか判定
    public static func matchesTriggerPattern(_ text: String) -> Bool {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return false }

        // 句点やクエスチョンマークがあるか
        if trimmed.hasSuffix("？") || trimmed.hasSuffix("?") {
            return true
        }

        // 語尾マッチング
        for pattern in endPatterns {
            if trimmed.hasSuffix(pattern) {
                return true
            }
        }
        return false
    }

    /// 自動送信すべき無音ディレイ秒数（トリガー一致時は素早く、それ以外は長め）
    public static func requiredSilenceDuration(for text: String) -> TimeInterval {
        if matchesTriggerPattern(text) {
            return 0.7  // 質問・依頼語尾なら0.7秒の無音で即送信
        } else {
            return 1.6  // 通常の発話なら1.6秒の無音で送信
        }
    }
